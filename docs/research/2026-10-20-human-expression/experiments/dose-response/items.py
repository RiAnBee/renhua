HEAD = """
【写作情境】
身份：{identity}
读者：{reader}
可用材料：
{facts}
读者已知：{known}
后果：{consequence}
写作要求：材料里的数字、时间、机构名按原样使用；材料之外的具体数字、文件号、人名不要编造。
"""

NO_FACTS = """
【写作情境】
身份：{identity}
读者：{reader}
可用材料：无（本次不提供任何具体事实）。不要编造数字、时间、机构名、文件号、人名。
读者已知：{known}
后果：{consequence}
写作要求：材料之外的具体数字、文件号、人名不要编造。
"""


def facts_for(item: dict, n: int) -> list[str]:
    full = list(item["facts"]) + EXTRA[item["id"]]
    assert len(full) == 10, (item["id"], len(full))
    return full[:n]


def prompt(item: dict, n: int) -> str:
    base = BASE[item["genre"]].format(topic=item["topic"]) + TAIL
    facts = facts_for(item, n)
    if not facts:
        return base + NO_FACTS.format(identity=item["identity"], reader=item["reader"],
                                      known=item["known"], consequence=item["consequence"])
    body = "\n".join(f"{i+1}) {f}" for i, f in enumerate(facts))
    return base + HEAD.format(identity=item["identity"], reader=item["reader"], facts=body,
                              known=item["known"], consequence=item["consequence"])


def main() -> int:
    assert len(EXTRA) == 30 and all(len(v) == 5 for v in EXTRA.values())
    rows = []
    for it in ITEMS:
        for n in DOSES:
            cell = f"d{n}"
            rows.append({"id": f"{it['id']}@{cell}", "item": it["id"], "cell": cell, "dose": n,
                         "genre": it["genre"], "topic": it["topic"],
                         "facts": facts_for(it, n), "tokens": it["tokens"],
                         "prompt": prompt(it, n)})
    assert len(rows) == 120
    HERE.joinpath("items.json").write_text(json.dumps(rows, ensure_ascii=False, indent=1))
    print("rows", len(rows), "per cell", {f"d{n}": sum(1 for r in rows if r["cell"] == f"d{n}") for n in DOSES})
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
